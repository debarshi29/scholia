"""Planted bugs (Tier 2): a deterministic mutation of a tested algorithm file.

Owner's request (14 Nov 2026): data-structure, algorithm and competitive-programming style
problems. The source is a repo whose files carry doctests (TheAlgorithms/Python, MIT). For
a file, one small mutation is applied (``<`` to ``<=``, ``+`` to ``-``, a constant moved by
one). A mutant is kept only if the file's doctests pass before and fail after it, so every
problem has a bug that a real test catches, and the answer key is the reverse of the
mutation. Nothing is generated by a model: the same seed gives the same problems.

The gold ``patch`` is the fix (buggy to clean). The buggy text is passed in
``Candidate.buggy_files``, because it exists nowhere upstream.

Doctests are run with the interpreter that runs the build, in a scratch directory holding
only that file, with a timeout. That executes upstream code from the cloned repo: it is the
same trust as running its test suite.
"""

import ast
import difflib
import random
import re
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

from git import Repo

from corpus.sources.base import Candidate
from corpus.text import line_count, split_lines
from schema import Source

REPO = "TheAlgorithms/Python"
REPO_URL = f"https://github.com/{REPO}.git"
MIN_LINES = 60
"""Algorithm files are short; the global 150-line minimum would leave almost none."""
DIRS = (
    "sorts",
    "searches",
    "dynamic_programming",
    "graphs",
    "data_structures",
    "maths",
    "strings",
    "greedy_methods",
    "backtracking",
    "divide_and_conquer",
    "bit_manipulation",
    "matrix",
)
TIMEOUT_S = 20
MIN_PASSING_TESTS = 3
_RESULT = re.compile(r"(\d+) passed and (\d+) failed")


@dataclass(frozen=True)
class Mutation:
    kind: str
    line: int
    """1-indexed line of the buggy text that changed."""
    text: str
    """The mutated file."""


_FLIP = {"<": "<=", "<=": "<", ">": ">=", ">=": ">"}


def _char(line: str, byte_col: int) -> int:
    """``ast`` columns are UTF-8 byte offsets; this is the character index."""
    return len(line.encode("utf-8")[:byte_col].decode("utf-8", errors="ignore"))


def mutations(source: str) -> list[Mutation]:
    """Every single-edit mutant of ``source`` that still parses, one per distinct text,
    in source order."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    lines = source.split("\n")
    out: dict[str, Mutation] = {}

    def edit(row: int, start: int, end: int, new: str, kind: str) -> None:
        """Replace characters [start, end) of 0-indexed line ``row``."""
        mutated = list(lines)
        mutated[row] = lines[row][:start] + new + lines[row][end:]
        text = "\n".join(mutated)
        try:
            ast.parse(text)
        except SyntaxError:
            return
        out.setdefault(text, Mutation(kind, row + 1, text))

    def gap(left: ast.expr, right: ast.expr) -> tuple[int, int, int] | None:
        """Row and character span between two operands on one line."""
        if left.end_lineno is None or left.end_lineno != right.lineno:
            return None
        row = left.end_lineno - 1
        return row, _char(lines[row], left.end_col_offset or 0), _char(lines[row], right.col_offset)

    for node in ast.walk(tree):
        if isinstance(node, ast.Compare) and len(node.ops) == 1:
            sym = {ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">="}.get(type(node.ops[0]))
            span = gap(node.left, node.comparators[0])
            if sym and span:
                row, a, b = span
                text = lines[row][a:b]
                if text.strip() == sym:
                    at = a + text.index(sym)
                    edit(row, at, at + len(sym), _FLIP[sym], "boundary")
        elif isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub)):
            span = gap(node.left, node.right)
            if span:
                row, a, b = span
                sym = "+" if isinstance(node.op, ast.Add) else "-"
                text = lines[row][a:b]
                if text.strip() == sym:
                    at = a + text.index(sym)
                    edit(row, at, at + 1, "-" if sym == "+" else "+", "logic")
        elif (
            isinstance(node, ast.Constant)
            and type(node.value) is int
            and node.value in (0, 1, 2)
            and node.end_lineno == node.lineno
            and node.end_col_offset is not None
        ):
            row = node.lineno - 1
            a, b = _char(lines[row], node.col_offset), _char(lines[row], node.end_col_offset)
            edit(row, a, b, str(node.value + 1), "boundary")
    return sorted(out.values(), key=lambda m: m.line)


def doctest_result(name: str, text: str) -> tuple[int, int] | None:
    """``(passed, failed)`` of the file's doctests, or ``None`` if they could not run."""
    with tempfile.TemporaryDirectory(prefix="scholia-planted-") as tmp:
        (Path(tmp) / name).write_text(text, encoding="utf-8")
        try:
            proc = subprocess.run(
                [sys.executable, "-m", "doctest", "-v", name],
                cwd=tmp,
                capture_output=True,
                text=True,
                timeout=TIMEOUT_S,
                check=False,
            )
        except subprocess.TimeoutExpired:
            return None
    found = _RESULT.findall(proc.stdout)
    if not found:
        return None
    passed, failed = found[-1]
    return int(passed), int(failed)


def fix_patch(path: str, buggy: str, clean: str) -> str:
    """The reverse of the mutation, as a git diff from the buggy text to the clean one."""
    body = "\n".join(
        difflib.unified_diff(
            split_lines(buggy),
            split_lines(clean),
            fromfile=f"a/{path}",
            tofile=f"b/{path}",
            n=3,
            lineterm="",
        )
    )
    return f"diff --git a/{path} b/{path}\n{body}\n"


def _clone(root: Path) -> tuple[Path, str]:
    path = root / "TheAlgorithms__Python__work"
    if not (path / ".git").exists():
        root.mkdir(parents=True, exist_ok=True)
        Repo.clone_from(REPO_URL, path, depth=1)
    return path, str(Repo(path).head.commit.hexsha)


class PlantedBugs:
    source = Source.PLANTED

    def __init__(
        self,
        root: Path,
        *,
        wanted: int,
        seed: int = 20261114,
        done: frozenset[str] = frozenset(),
    ) -> None:
        self.root = root
        self.wanted = wanted
        self.seed = seed
        self.done = done
        """Files that already have a published problem. They are skipped before any doctest runs,
        so a re-run moves on to new files instead of re-finding the same ones."""

    def _files(self, work: Path) -> list[str]:
        found: list[str] = []
        for d in DIRS:
            for p in sorted((work / d).rglob("*.py")):
                name = p.name
                if name.startswith("test_") or name == "__init__.py":
                    continue
                found.append(p.relative_to(work).as_posix())
        random.Random(self.seed).shuffle(found)
        return found

    def candidates(self) -> Iterator[Candidate]:
        work, commit = _clone(self.root)
        yielded = 0
        for rel in self._files(work):
            if yielded >= self.wanted:
                return
            if rel in self.done:
                continue
            clean = (work / rel).read_text(encoding="utf-8", errors="replace")
            if not MIN_LINES <= line_count(clean) <= 500:
                continue
            base = doctest_result(Path(rel).name, clean)
            if base is None or base[1] != 0 or base[0] < MIN_PASSING_TESTS:
                continue
            muts = mutations(clean)
            if not muts:
                continue
            for mut in random.Random(f"{self.seed}:{rel}").sample(muts, min(len(muts), 6)):
                after = doctest_result(Path(rel).name, mut.text)
                if after is None or after[1] == 0:
                    continue  # no test noticed it, or it hung: not a good problem
                yielded += 1
                yield Candidate(
                    source=Source.PLANTED,
                    upstream_id=f"{rel}#{mut.kind}@{mut.line}",
                    repo=REPO,
                    commit=commit,
                    patch=fix_patch(rel, mut.text, clean),
                    issue=(
                        f"{after[1]} of {after[0] + after[1]} doctests in {rel} fail. "
                        "Infer the defect from the code and the fix."
                    ),
                    failing_tests=[f"python -m doctest {rel}"],
                    buggy_files={rel: mut.text},
                    min_lines=MIN_LINES,
                )
                break
